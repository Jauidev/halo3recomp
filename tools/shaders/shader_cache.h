#pragma once

#include <cstdint>
#include <cstddef>

struct ShaderCacheEntry
{
    const uint64_t hash;
    const uint32_t dxilOffset;
    const uint32_t dxilSize;
    const uint32_t spirvOffset;
    const uint32_t spirvSize;
    const uint32_t lateSpirvOffset;
    const uint32_t lateSpirvSize;
    const uint32_t airOffset;
    const uint32_t airSize;
    const uint32_t specConstantsMask;
    char filename[256];
    struct GuestShader* guestShader;
    // Xenos texture-fetch constant slots referenced by the guest microcode.
    // This is deliberately stored after guestShader so a checked-in cache
    // generated by the preceding schema remains source-compatible until the
    // complete shader corpus is regenerated. The sentinel makes a legacy
    // entry fail closed instead of being mistaken for a shader that samples
    // no textures.
    const uint32_t usedTextureMask = UINT32_MAX;
    // Xcompiler (Halo 3): vertex fetch slots (0-95) a vertex shader with computed fetch indices
    // reads itself from guest memory (XenosRecomp's XcFetchVertex); zero for every other shader.
    const uint32_t vertexFetchSlots[3] = {0, 0, 0};
    // Xcompiler (Halo 3, 2026-11-10): the patch fetch plan of a vertex shader drawn with
    // tessellated patches (XenosRecomp's shader_recompiler.h): its leading vertex fetches that
    // depend only on the patch index, which the renderer may run once per patch (XcPatchFetch).
    // Entries with bit 31 set, in the shader's order; none for every other shader.
    const uint32_t patchPlan[32] = {};
};

extern ShaderCacheEntry g_shaderCacheEntries[];
extern const size_t g_shaderCacheEntryCount;

extern const uint8_t g_compressedDxilCache[];
extern const size_t g_dxilCacheCompressedSize;
extern const size_t g_dxilCacheDecompressedSize;

extern const uint8_t g_compressedAirCache[];
extern const size_t g_airCacheCompressedSize;
extern const size_t g_airCacheDecompressedSize;

extern const uint8_t g_compressedSpirvCache[];
extern const size_t g_spirvCacheCompressedSize;
extern const size_t g_spirvCacheDecompressedSize;
