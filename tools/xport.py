def run(args, output=None, timeout=None):
    """Runs a command; returns (exit code, stdout + stderr). A timeout comes back as exit code None."""
    try:
        done = subprocess.run(args, capture_output=True, timeout=timeout)
    except subprocess.TimeoutExpired as e:
        done = None
        text = (e.stdout or b"").decode("utf-8", "replace")
    if done is not None:
        text = done.stdout.decode("utf-8", "replace")
    if output and done is not None:
        with open(output, "w", encoding="utf-8") as f:
            f.write(text)
    if done is None:
        return None, text
    return done.returncode, text + done.stderr.decode("utf-8", "replace")


def tool(script, *args, output=None):
    code, text = run([sys.executable, "-I", os.path.join(TOOLS, script), *args], output)
    if code != 0:
        raise SystemExit(f"{script} failed ({code}):\n{text[-2000:]}")
    return text


def step(message):
    print(f"[{time.strftime('%H:%M:%S')}] {message}", flush=True)


def folder_listing(folder):
    return ["/" + os.path.relpath(os.path.join(d, n), folder).replace("\\", "/") for d, _, names in os.walk(folder) for n in names]


def read_input(source, out, extract=False):
    """Puts default.xex in out; returns the disc listing (empty when given a bare XEX).
    The source: a disc ISO, an Xbox Live Arcade package (CON/LIVE/PIRS), an extracted disc folder
    or a bare XEX. With extract, or for a package, every file goes to out/disc (the game folder the
    boot test runs and tools/shaders.py reads)."""
    xex = os.path.join(out, "default.xex")
    disc = os.path.join(out, "disc")
    sys.path.insert(0, TOOLS)
    import stfs
    if os.path.isdir(source):
        listing = folder_listing(source)
        found = os.path.join(source, "default.xex")
        if not os.path.exists(found):
            raise SystemExit(f"{source}: no default.xex in the folder")
        shutil.copyfile(found, xex)
        return listing
    if stfs.is_package(source):
        package = stfs.Package(source)
        step(f"Paquete {package.magic}: {package.display_name}, {len(package.entries)} archivos")
        package.extract(disc)
        listing = folder_listing(disc)
        found = [p for p in listing if p.lower().endswith("/default.xex")] or [p for p in listing if p.lower().endswith(".xex")]
        if not found:
            raise SystemExit(f"{source}: the package holds no .xex")
        shutil.copyfile(os.path.join(disc, *found[0].strip("/").split("/")), xex)
        return listing
    if not source.lower().endswith(".iso"):
        shutil.copyfile(source, xex)
        return []
    listing = tool("xdvdfs.py", source, "list", output=os.path.join(out, "disc.txt"))
    tool("xdvdfs.py", source, "extract", "/default.xex", xex)
    if extract:
        step("Extrayendo el disco entero...")
        tool("xdvdfs.py", source, "extractall", disc)
    return [line.split(None, 2)[2] for line in listing.splitlines() if line.startswith("F ")]


def parse_info(text):
    field = lambda name: (re.search(rf"^{name} = (.+)$", text, re.M) or [None, "?"])[1]
    return {
        "title_id": field("title_id"), "media_id": field("media_id"), "version": field("version"),
        "pe_name": field("original_pe_name"), "base": field("load_address"),
        "sections": [(m[1], int(m[2], 16), int(m[3], 16), m[4]) for m in
                     re.finditer(r"^section (\S+)\s+base=0x([0-9A-F]+) size=0x([0-9A-F]+) (\w+)", text, re.M)],
        "libraries": re.findall(r"^(\w+)\s+(\d+\.\d+\.\d+\.\d+)$", text, re.M),
        "functions": re.findall(r"^\S+ func 0x[0-9A-F]+ (?:__imp__)?(\S+) ", text, re.M),
        "variables": re.findall(r"^\S+ var  0x[0-9A-F]+ (?:__imp__)?(\S+) ", text, re.M),
    }


def find_helpers(scan):
    """Returns (found, problems). With several hits the first is used, as it was by hand for GTA."""
    found, problems = {}, []
    for name in HELPERS:
        # strip(): the scan's lines end in \r\n on Windows, and "NOT FOUND\r" went into game.toml as
        # a value (Halo 3's Waves DLLs have no VMX helpers; XenonRecomp died on the config).
        hits = re.search(rf"^{name}_address = (.+)$", scan, re.M)[1].strip()
        if hits == "NOT FOUND":
            problems.append(f"`{name}` no aparece con el patrón habitual")
            continue
        hits = hits.split(", ")
        found[name] = hits[0]
        if len(hits) > 1:
            problems.append(f"`{name}` aparece {len(hits)} veces; se usa {hits[0]}")
    return found, problems


def recompile(out, log_path):
    """One clean XenonRecomp run (it does not delete leftover files) and what it complained about."""
    ppc = os.path.join(out, "ppc")
    shutil.rmtree(ppc, ignore_errors=True)
    # exist_ok: on Windows a folder something has open (a shell's current directory, Explorer) loses
    # its files but stays
    os.makedirs(ppc, exist_ok=True)
    started = time.time()
    code, log = run([XENON_RECOMP, os.path.join(out, "game.toml"), PPC_CONTEXT], log_path, RECOMPILE_TIMEOUT)
    branch_errors = 0
    for path in glob.glob(os.path.join(ppc, "ppc_recomp.*.cpp")):
        with open(path, encoding="utf-8", errors="replace") as f:
            branch_errors += sum("// ERROR " in line for line in f)
    return {
        "exit": code, "seconds": time.time() - started, "branch_errors": branch_errors,
        "switch_errors": len(re.findall(r"Switch case at [0-9A-F]+ is trying", log)),
        "unknown": Counter(re.findall(r"Unrecognized instruction at 0x[0-9A-F]+: (\S+)", log)),
        "undecoded": len(re.findall(r"Unable to decode instruction", log)),
        "pack": len(re.findall(r"Unexpected .* instruction at", log)),
        "config_errors": re.findall(r"^ERROR: .*address is unspecified$", log, re.M),
    }


def recompile_until_stable(out):
    """Repeats the fixes the GTA IV ports needed by hand until XenonRecomp has nothing left to report."""
    config = os.path.join(out, "game.toml")
    pe = os.path.join(out, "default.pe")
    tables = os.path.join(out, "switch_tables.toml")
    log = os.path.join(out, "xenonrecomp.log")
    entries = os.path.join(out, "entries.tmp")
    ppc = os.path.join(out, "ppc")

    merges = [0]

    def merge(text):
        """Adds function entries to the config; True when that changed it."""
        with open(entries, "w") as f:
            f.write(text)
        # Halo 3: every merge's entries kept (logs/merge-<n>.txt), to find which fixer wrote what.
        merges[0] += 1
        os.makedirs(os.path.join(out, "logs"), exist_ok=True)
        with open(os.path.join(out, "logs", f"merge-{merges[0]}.txt"), "w") as f:
            f.write(text)
        with open(config) as f:
            before = f.read()
        tool("merge_functions.py", config, entries)
        with open(config) as f:
            return f.read() != before

    merge(tool_stdout("find_chunks.py", pe))
    # Halo 3: leaf functions (no .pdata) with their whole extent, so their jump tables stay inside.
    merge(tool_stdout("gap_functions.py", pe, tables))
    rounds = []
    for number in range(1, MAX_ROUNDS + 1):
        step(f"XenonRecomp, ronda {number}...")
        stats = recompile(out, log)
        rounds.append(stats)
        step(f"  {stats['seconds']:.0f} s, salida {stats['exit']}: {stats['branch_errors']} saltos a otra función, "
             f"{stats['switch_errors']} switch fuera de función, {sum(stats['unknown'].values())} instrucciones desconocidas")
        mapping = os.path.join(ppc, "ppc_func_mapping.cpp")
        if stats["exit"] != 0 or not os.path.exists(mapping):
            break
        # One kind of fix at a time, each on boundaries the one before has settled. A function still cut
        # short by its switch shows branches and pointers into its other half that look like entries,
        # and declaring one splits the function for good (merge only ever adds).
        changed = False
        # Halo 3: the round's mapping kept beside the merges (the next round deletes ppc/).
        shutil.copyfile(mapping, os.path.join(out, "logs", f"mapping-{number}.cpp"))
        if stats["switch_errors"]:
            changed = merge(tool_stdout("fix_switch.py", pe, tables, log, config, mapping))
        if not changed and stats["branch_errors"]:
            changed = merge(tool_stdout("fix_branches.py", ppc, config))
        if not changed:
            changed = merge(tool_stdout("find_fnptrs.py", pe, mapping))
        if not changed:
            break
    os.remove(entries)
    return rounds


def tool_stdout(script, *args):
    """A scan tool's entries only: its stats go to stderr."""
    temp = os.path.join(os.path.dirname(args[0]) if os.path.isfile(args[0]) else args[0], script + ".tmp")
    tool(script, *args, output=temp)
    with open(temp, encoding="utf-8") as f:
        text = f.read()
    os.remove(temp)
    return text


def runtime_imports():
    """Imports the runtime answers: name -> True when real, False when it only logs (Unimplemented_)."""
    known = {}
    pattern = re.compile(r"GUEST_FUNCTION_(HOOK|STUB)\(\s*__imp__(\w+)\s*(?:,\s*(\w+))?")
    for tree in ("runtime", "rexglue_glue", "xenia_glue"):
        for folder, _, names in os.walk(os.path.join(ROOT, tree)):
            for name in names:
                path = os.path.join(folder, name)
                if not name.endswith((".cpp", ".cc", ".h")) or os.path.getsize(path) > 5 << 20:
                    continue
                with open(path, encoding="utf-8", errors="replace") as f:
                    for kind, imported, target in pattern.findall(f.read()):
                        known[imported] = kind == "HOOK" and not target.startswith("Unimplemented_")
    return known


def find_setjmp(pe, sections):
    """Register-save runs into r3 (std r14.., d(r3)), which is what setjmp looks like. XenonRecomp must
    be told about setjmp/longjmp or the recompiled ones crash; finding none is what GTA gives.
    Returns (hits, {"setjmp": address, "longjmp": address}) with the second filled only when the CRT
    pair is recognised: setjmp saves CR (mfcr) and returns 0, longjmp reloads r14.. and CR (mtcrf)."""
    BLR, MASK_MFCR, MFCR, MASK_MTCRF, MTCRF = 0x4E800020, 0xFC1FFFFF, 0x7C000026, 0xFC100FFF, 0x7C000120

    def run_of(words, i, opcode, base_reg=None):
        """True when words[i..i+9] are opcode r14..r23, d(rA) with one rA (not r1, the stack)."""
        ra = (words[i] >> 16) & 31
        return ra != 1 and (base_reg is None or ra == base_reg) and all(
            words[i + k] >> 26 == opcode and words[i + k] & 3 == 0 and (words[i + k] >> 16) & 31 == ra
            and (words[i + k] >> 21) & 31 == 14 + k for k in range(10))

    def start_of(words, i):
        """CRT routines sit between padding (0) or the blr that ends the one before."""
        limit = max(0, i - 256)
        while i > limit and words[i - 1] not in (0, BLR):
            i -= 1
        return i

    def has(words, first, last, mask, value):
        return any(words[j] & mask == value for j in range(first, min(last, len(words))))

    # How far after the register run the blr may be. The CRT of XDK 2.0.20500 (Gears of War 3) also
    # saves and reloads v64..v127 (li + stvlx128/lvx128 each: 128 more words) before it returns.
    REACH = 256
    hits, found = [], {}
    for _, base, size, kind in sections:
        if kind != "code":
            continue
        words = struct.unpack_from(f">{size // 4}I", pe, base - IMAGE_BASE)
        for i in range(len(words) - 10):
            if not run_of(words, i, 62, 3):
                continue
            hits.append(base + 4 * i)
            if found:
                continue
            start = start_of(words, i)
            end = next((j for j in range(i, min(i + REACH, len(words))) if words[j] == BLR), None)
            if end is None or words[end - 1] != 0x38600000 or not has(words, start, i, MASK_MFCR, MFCR):  # li r3,0
                continue
            # longjmp: the nearest reload run that restores CR before returning
            near = [j for j in range(max(0, i - 512), min(len(words) - 10, i + 512)) if run_of(words, j, 58)]
            for j in sorted(near, key=lambda j: abs(j - i)):
                ret = next((k for k in range(j, min(j + REACH, len(words))) if words[k] == BLR), None)
                if ret is not None and has(words, j, ret, MASK_MTCRF, MTCRF):
                    found = {"setjmp": base + 4 * start, "longjmp": base + 4 * start_of(words, j)}
                    break
    return hits, found


def identify(pe, disc):
    """Engine and middleware hints: {name: (strings found, disc files that match)}."""
    def count(needles):
        return sum(pe.count(n) + pe.count(n.decode().encode("utf-16-be")) for n in needles)

    extensions = Counter(os.path.splitext(path)[1].lower() for path in disc)
    engines = {}
    for name, (needles, exts) in ENGINES.items():
        strings, files = count(needles), sum(extensions[e] for e in exts)
        if strings or files:
            engines[name] = (strings, files)
    middleware = [name for name, needles in MIDDLEWARE.items() if count(needles)]
    return sorted(engines.items(), key=lambda e: (-(e[1][0] > 0 and e[1][1] > 0), -e[1][0], -e[1][1])), middleware, extensions


def write_report(path, info, disc, helper_problems, rounds, known, setjmp, pe, out):
    last = rounds[-1]
    engines, middleware, extensions = identify(pe, disc)
    missing = sorted(set(info["functions"]) - set(known))
    stubs = sorted(n for n in info["functions"] if n in known and not known[n])
    real = sum(1 for n in info["functions"] if known.get(n))
    mapping = os.path.join(out, "ppc", "ppc_func_mapping.cpp")
    functions = 0
    if os.path.exists(mapping):
        with open(mapping, encoding="utf-8", errors="replace") as f:
            functions = len(re.findall(r"\{ 0x[0-9A-F]+, sub_", f.read()))
    with open(os.path.join(out, "game.toml")) as f:
        entries = len(re.findall(r"address = 0x", f.read()))
    code = sum(size for _, _, size, kind in info["sections"] if kind == "code")
    other_xex = [p for p in disc if p.lower().endswith((".xex", ".xexp")) and p.lower() != "/default.xex"]
    libs = dict(info["libraries"])

    clean = last["exit"] == 0 and functions and not (last["branch_errors"] or last["switch_errors"] or last["unknown"])
    blockers = []
    if last["exit"] != 0:
        blockers.append("XenonRecomp no terminó (salida %s)" % last["exit"])
    if last["unknown"]:
        blockers.append(f"{len(last['unknown'])} tipos de instrucción sin implementar en XenonRecomp")
    if last["branch_errors"] or last["switch_errors"]:
        blockers.append(f"quedan {last['branch_errors']} saltos y {last['switch_errors']} switch sin resolver")
    risks = list(helper_problems)
    if missing:
        risks.append(f"{len(missing)} imports que el runtime no tiene: el build les pone stubs que solo registran la "
                     "llamada (`tools/gen_stubs.py`), así que enlaza; si el juego depende de alguno, hay que escribirlo "
                     "en `runtime/kernel/`.")
    hits, jumps = setjmp
    if jumps:
        risks.append(f"Usa `setjmp`/`longjmp` del CRT (0x{jumps['setjmp']:08X} y 0x{jumps['longjmp']:08X}): ya van en "
                     "`game.toml` y el código recompilado llama a los del sistema. Las variables locales que cambien "
                     "entre los dos pueden perder su valor; si algo falla tras un error del juego, mirar ahí.")
    elif hits:
        risks.append("Parece usar `setjmp` (" + ", ".join(f"0x{a:08X}" for a in hits[:4]) + ") pero no se reconoció "
                     "el par del CRT: hay que comprobarlo y declarar `setjmp_address` y `longjmp_address` en "
                     "`game.toml`; sin eso falla en ejecución.")
    if set(info["functions"]) & {"RtlRaiseException", "RtlUnwind", "__C_specific_handler"}:
        risks.append("Importa funciones de excepciones. XenonRecomp no las admite: si el juego depende de ellas para "
                     "funcionar, habrá que parchear esos sitios.")
    if other_xex:
        risks.append("Hay más ejecutables en el disco (" + ", ".join(other_xex[:6]) + "). Cada uno se recompila aparte.")
    if last["pack"]:
        risks.append(f"{last['pack']} instrucciones D3D de empaquetado con variantes inesperadas.")
    if stubs:
        risks.append(f"{len(stubs)} imports son solo stubs en el runtime y pueden necesitar lógica real: "
                     + ", ".join(f"`{n}`" for n in stubs[:12]) + ("..." if len(stubs) > 12 else ""))

    lines = [f"# Informe de port: {info['pe_name']} (título {info['title_id']})", ""]
    lines += ["## Veredicto", ""]
    if clean:
        lines += ["**Fase 1 superada:** recompila limpio" + (" y el runtime cubre sus imports. " if not missing else
                  f"; {len(missing)} imports quedan como stubs. ") +
                  "Eso no garantiza que arranque; siguiente paso, enlazarlo y ejecutarlo en el PC.", ""]
    else:
        lines += ["**Quedan bloqueos antes de poder enlazar:**", ""] + [f"- {b}" for b in blockers] + [""]

    lines += ["## Identidad", "",
              f"- Título {info['title_id']}, media {info['media_id']}, versión del XEX {info['version']}",
              f"- XDK {libs.get('D3D9') or libs.get('XAPILIB') or '?'}; librerías: " + ", ".join(sorted(libs)),
              f"- Código: {code / 1048576:.1f} MB en " + ", ".join(n for n, _, _, k in info["sections"] if k == "code"), ""]

    lines += ["## Motor (indicios, sin verificar)", ""]
    if engines:
        lines += [f"- {name}: {strings} cadenas en el ejecutable, {files} archivos del disco" for name, (strings, files) in engines]
    else:
        lines += ["- Ninguno de los conocidos."]
    if middleware:
        lines += [f"- Middleware: {', '.join(middleware)}"]
    if extensions:
        top = ", ".join(f"{ext or '(sin extensión)'} ×{n}" for ext, n in extensions.most_common(8))
        lines += [f"- Archivos del disco: {top}"]
    lines += [""]

    lines += ["## Recompilación", "",
              f"- {functions} funciones, {entries} límites en `game.toml`, {len(rounds)} rondas ({sum(r['seconds'] for r in rounds):.0f} s)",
              f"- Última ronda: {last['branch_errors']} saltos a otra función, {last['switch_errors']} switch fuera de función, "
              f"{last['undecoded']} palabras sin decodificar"]
    if last["unknown"]:
        lines += ["- Instrucciones sin implementar: " + ", ".join(f"`{op}` ×{n}" for op, n in last["unknown"].most_common())]
    lines += [""]

    lines += ["## Imports", "",
              f"- Funciones: {len(info['functions'])}. Implementadas: {real}. Solo stub: {len(stubs)}. **Faltan: {len(missing)}**"]
    if missing:
        lines += ["- Faltan: " + ", ".join(f"`{n}`" for n in missing)]
    if info["variables"]:
        lines += ["- Variables del kernel (revisar a mano): " + ", ".join(f"`{n}`" for n in info["variables"])]
    lines += [""]

    if risks:
        lines += ["## Riesgos", ""] + [f"- {r}" for r in risks] + [""]

    lines += ["## Gráficos", ""]
    lines += ["El renderizador nativo engancha las funciones D3D del XDK, no las del motor: sirve si `tools/find_d3d.py` "
              "(paso de la ranura, `tools/slot.py`) las encuentra todas y los shaders están en la caché (`tools/shaders.py`). "
              "La GPU de Xenia (`XPORT_GPU=xenia`) no depende de eso y separa los fallos del renderizador de los del juego; "
              "en el Poco X6 Pro, GTA IV dio 7-9 fps con ella y 13-22 con el nativo."]

    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    return "\n".join(lines)


def main():
    global IMAGE_BASE
    args = [a for a in sys.argv[1:] if a != "--extract"]
    if len(args) != 2:
        raise SystemExit(__doc__)
    source, out = os.path.abspath(args[0]), os.path.abspath(args[1])
    os.makedirs(out, exist_ok=True)
    sys.stdout.reconfigure(encoding="utf-8")

    step("Leyendo el juego...")
    disc = read_input(source, out, "--extract" in sys.argv)
    xex = os.path.join(out, "default.xex")
    pe_path = os.path.join(out, "default.pe")
    info_path = os.path.join(out, "xexinfo.txt")
    code, text = run([os.path.join(HOST, "xexinfo.exe"), xex, pe_path], info_path)
    if code != 0:
        raise SystemExit(f"xexinfo failed ({code}):\n{text[-2000:]}")
    with open(info_path, encoding="utf-8", errors="replace") as f:
        info = parse_info(f.read())
    if int(info["base"], 16) != IMAGE_BASE:
        # Halo 3: its Waves DLLs load at 0x88000000 and up. The scan tools take the base from
        # XPORT_IMAGE_BASE (0x82000000 when unset), passed to every tool run from here on.
        IMAGE_BASE = int(info["base"], 16)
        os.environ["XPORT_IMAGE_BASE"] = f"0x{IMAGE_BASE:08X}"
        step(f"Dirección de carga 0x{IMAGE_BASE:08X} (una DLL)")
    step(f"Título {info['title_id']}, {info['pe_name']}")

    step("Buscando las funciones de guardar y restaurar registros...")
    scan = tool("scan_pe.py", pe_path, info_path, output=os.path.join(out, "scan.txt"))
    helpers, helper_problems = find_helpers(scan)
    with open(pe_path, "rb") as f:
        pe = f.read()
    setjmp = find_setjmp(pe, info["sections"])
    helpers.update({n: f"0x{a:08X}" for n, a in setjmp[1].items()})
    if setjmp[1]:
        step(f"setjmp en 0x{setjmp[1]['setjmp']:08X}, longjmp en 0x{setjmp[1]['longjmp']:08X}")
    with open(os.path.join(out, "game.toml"), "w") as f:
        f.write(CONFIG.format(title_id=info["title_id"], version=info["version"],
                              helpers="\n".join(f"{n}_address = {helpers[n]}" for n in helpers)))

    step("Buscando tablas de saltos...")
    tables = os.path.join(out, "switch_tables.toml")
    code, text = run([XENON_ANALYSE, xex, tables])
    if code != 0:
        raise SystemExit(f"XenonAnalyse failed ({code}):\n{text[-2000:]}")
    with open(tables, "a") as f:
        f.write(tool_stdout("find_switches.py", pe_path, tables))
    # Halo 3: tables without a bounds check that XenonAnalyse read into the code after them.
    tool("trim_tables.py", pe_path, tables)
    # Halo 3: tables whose index register or length XenonAnalyse took from an unrelated compare
    # (sub_82086990 switched on r11 with one case instead of r10 with four).
    tool("check_switches.py", pe_path, tables, "--fix")

    rounds = recompile_until_stable(out)

    report = write_report(os.path.join(out, "report.md"), info, disc, helper_problems, rounds, runtime_imports(),
                          setjmp, pe, out)
    print("\n" + report)


if __name__ == "__main__":
    main()
