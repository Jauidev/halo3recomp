"""Takes any Xbox 360 game through phases 0 and 1 of a port: from its ISO or default.xex to a
XenonRecomp config that recompiles cleanly, plus a report of what stands between it and the runtime
(unknown instructions, imports the runtime lacks, engine, risks).

Writes into <output dir>: default.xex, default.pe, xexinfo.txt, scan.txt, switch_tables.toml,
game.toml, ppc/ (the recompiled code), xenonrecomp.log and report.md; with --extract (always for
an Xbox Live Arcade package) the whole disc in disc/. tools/port.py runs this and the steps after.

usage: py -3 -I tools/xport.py <game.iso|default.xex|XBLA package|disc folder> <output dir> [--extract]
"""
