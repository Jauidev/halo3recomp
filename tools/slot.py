"""Makes a game's slot, games/<name>/, from what tools/xport.py wrote (steps 3 and 5 of a port).

  slot.py <xport output dir> <name> [app label]

games/<name>/ gets:
  ppc/                  the recompiled code (on every run, only the files that changed)
  xd3d_functions.h      its D3D functions, by tools/find_d3d.py (again on every run, if changed)
  xd3d_device.h         its D3D device's fields, the same way
  runtime-imports.txt   its imports, for tools/gen_stubs.py (again on every run, if changed)
  game.cmake, game.cpp  title ID, XEX, app name; the runtime's questions (only when missing:
                        these are where the hand work goes)
  data/                 an empty shader cache (only when missing; tools/shaders.py fills it)
and <xport output dir>/d3d.json says what find_d3d found. Then:
  set XPORT_GAME=<name> & tools\\build-host.bat --target xport
"""
import filecmp, json, os, re, shutil, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TOOLS = os.path.join(ROOT, "tools")
SIGNATURES = os.path.join(TOOLS, "signatures")

GAME_CMAKE = """# {label} (generated by tools/slot.py). XPORT_TITLE_ID: from the XEX, it keys the pipeline cache
# on disk. XPORT_XEX_MEDIA / XPORT_XEX_VERSION: the XEX the launcher accepts (0: any).
set(XPORT_TITLE_ID {title_id})
set(XPORT_XEX_MEDIA {media_id})
set(XPORT_XEX_VERSION {version})
# The app's name on the phone (tools/build-apk.sh).
set(XPORT_APP_LABEL "{label}")
"""

GAME_CPP = """// {label}: what the runtime asks of the game (runtime/game.h). Generated by tools/slot.py:
// everything here is a default, to be replaced as the boot test (tools/boot_test.py) shows the need.
#include <stdafx.h>
#include <game.h>
#include <kernel/function.h>
#include <kernel/memory.h>
#include <os/logger.h>

namespace game
{{
    const char* Title()
    {{
        return "{label}";
    }}

    void RegisterExtraFunctions(Memory& memory)
    {{
        // Entry points the recompiler missed: memory.InsertFunction(address, function).
        (void)memory;
    }}

    const char* ThreadName(uint32_t startAddress, uint32_t startContext, uint32_t& entry)
    {{
        // The engine's render, audio and streaming threads, by entry point, to keep them on the
        // big cores (os/thread_policy.cpp). None known yet.
        (void)startAddress;
        (void)startContext;
        (void)entry;
        return nullptr;
    }}

    void AfterImageLoad()
    {{
    }}

    const char* RendererOptions()
    {{
        return "";
    }}

    bool PauseMenuOpen()
    {{
        return false;
    }}
}}
"""


def field(text, name):
    m = re.search(rf"^{name} = (0x[0-9A-Fa-f]+)$", text, re.M)
    return m[1] if m else "0"


def imports(text):
    names = []
    for name in re.findall(r"^\S+ func 0x[0-9A-F]+ (?:__imp__)?(\S+) ", text, re.M):
        if name not in names:
            names.append(name)
    return names


def best_database(info_text):
    """The signature database of the same XDK, else the only one there is."""
    libs = dict(re.findall(r"^(\w+)\s+(\d+\.\d+\.\d+\.\d+)$", info_text, re.M))
    xdk = libs.get("D3D9") or libs.get("D3D9LTCG", "")  # D3D9LTCG: built with link-time code generation
    databases = sorted(f for f in os.listdir(SIGNATURES) if f.endswith(".json"))
    for name in databases:
        if xdk.startswith(name[len("xdk-"):-len(".json")]):
            return os.path.join(SIGNATURES, name)
    return os.path.join(SIGNATURES, databases[-1])


def write(path, text, keep=False):
    """Writes path unless keep and it exists. A file whose text has not changed keeps its date, so
    the build does not compile again what depends on it."""
    if os.path.exists(path):
        if keep:
            return False
        with open(path, encoding="utf-8", newline="") as f:
            if f.read() == text:
                return False
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return True


def sync_file(src, dst):
    """Copies src to dst only when they differ (same reason as write)."""
    if os.path.exists(dst) and filecmp.cmp(src, dst, shallow=False):
        return
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    shutil.copyfile(src, dst)


def sync_tree(src, dst):
    """Makes dst a copy of src, rewriting only the files that changed and removing the ones gone. XenonRecomp
    writes every file again on each run; copying them all would make the build recompile all of ppc/."""
    wanted = set()
    for folder, _, names in os.walk(src):
        for n in names:
            rel = os.path.relpath(os.path.join(folder, n), src)
            wanted.add(rel)
            sync_file(os.path.join(src, rel), os.path.join(dst, rel))
    for folder, _, names in os.walk(dst):
        for n in names:
            if os.path.relpath(os.path.join(folder, n), dst) not in wanted:
                os.remove(os.path.join(folder, n))


def make_slot(out, name, label=None):
    if not re.fullmatch(r"[a-z0-9_]+", name):
        raise SystemExit(f"slot name '{name}': lowercase letters, digits and _ only (it names the APK package)")
    info_path = os.path.join(out, "xexinfo.txt")
    mapping = os.path.join(out, "ppc", "ppc_func_mapping.cpp")
    if not os.path.exists(mapping):
        raise SystemExit(f"{out}: no ppc/ppc_func_mapping.cpp, run tools/xport.py first")
    info = open(info_path, encoding="utf-8", errors="replace").read()
    slot = os.path.join(ROOT, "games", name)
    # It goes into a C++ string and a CMake one.
    label = re.sub(r'["\\$;{}]', "", label or name).strip() or name
    made = []

    sync_tree(os.path.join(out, "ppc"), os.path.join(slot, "ppc"))

    database = best_database(info)
    header = os.path.join(out, "xd3d_functions.h")
    # What was checked by hand in this game (written by hand, kept): it wins over the search.
    fixes = os.path.join(slot, "xd3d_fixes.txt")
    run = subprocess.run([sys.executable, "-I", os.path.join(TOOLS, "find_d3d.py"), "find", os.path.join(out, "default.pe"),
                          info_path, database, header, mapping] + ([fixes] if os.path.exists(fixes) else []),
                         capture_output=True, text=True)
    if run.returncode:
        raise SystemExit(f"find_d3d.py failed:\n{run.stdout[-1500:]}{run.stderr[-1500:]}")
    sync_file(header, os.path.join(slot, "xd3d_functions.h"))
    sync_file(os.path.join(out, "xd3d_device.h"), os.path.join(slot, "xd3d_device.h"))
    d3d =json.loads(run.stdout[run.stdout.index("{"):])
    d3d["database"] = os.path.basename(database)
    with open(os.path.join(out, "d3d.json"), "w") as f:
        json.dump(d3d, f, indent=1)

    names = imports(info)
    write(os.path.join(slot, "runtime-imports.txt"), "\n".join(names) + "\n")

    version = field(info, "version")
    if write(os.path.join(slot, "game.cmake"), GAME_CMAKE.format(
            label=label, title_id=field(info, "title_id"), media_id=field(info, "media_id"), version=version), keep=True):
        made.append("game.cmake")
    if write(os.path.join(slot, "game.cpp"), GAME_CPP.format(label=label), keep=True):
        made.append("game.cpp")
    if not os.path.exists(os.path.join(slot, "data", "shader", "shader_cache.cpp")):
        subprocess.run([sys.executable, "-I", os.path.join(TOOLS, "shaders.py"), "empty", name], check=True,
                       capture_output=True)
        made.append("data/")

    result = {"slot": f"games/{name}", "new_files": made, "imports": len(names), "d3d": d3d}
    with open(os.path.join(out, "slot.json"), "w") as f:
        json.dump(result, f, indent=1)
    print(f"games/{name}: {len(names)} imports, D3D {d3d['found']}/{d3d['total']} functions "
          f"({'same' if d3d['same_xdk'] else 'other'} XDK {d3d['xdk']}"
          + (f", {len(d3d['similar'])} by likeness" if d3d.get("similar") else "")
          + f"), data {d3d['data_found']}/{d3d['data_total']}" + (f"; new: {', '.join(made)}" if made else ""))
    return result


if __name__ == "__main__":
    if len(sys.argv) not in (3, 4):
        raise SystemExit(__doc__)
    make_slot(os.path.abspath(sys.argv[1]), sys.argv[2], sys.argv[3] if len(sys.argv) == 4 else None)
